"""aggregate.py — Statistical aggregation over runner output.

Reads a JSON file produced by ``experiments.runner`` and computes:
  - mean ± std for each numeric metric, per policy
  - 95% confidence intervals (central z, via ``metrics.statistics``)
  - paired t-statistic for each (DQN, baseline) pair

Writes both a flat JSON and a Markdown summary table.

Usage:
    python -m experiments.aggregate --input smoke.json \\
        --output experiments/results/REPORT.md
"""
from __future__ import annotations

import argparse
import json
import logging
import os
import sys
from typing import Dict, List

THIS_DIR = os.path.dirname(os.path.abspath(__file__))
BACKEND_ROOT = os.path.dirname(THIS_DIR)
if BACKEND_ROOT not in sys.path:
    sys.path.insert(0, BACKEND_ROOT)

from metrics.statistics import (  # noqa: E402
    mean, std, ci95, paired_t, is_significant, summarise,
)

logger = logging.getLogger(__name__)


# Metrics to aggregate. All numbers are floats.
_METRICS = [
    "elapsed_s", "actions_taken", "n_failed_end",
    "n_isolated_end", "avg_voltage_end", "total_energy_loss_end",
]


def _per_policy(runs: List[dict]) -> Dict[str, List[dict]]:
    """Group runs by policy label.

    Accepts both the legacy shape (``r['policy']`` + ``r['valid']``)
    and the new shape (``r['controller_label']`` +
    ``r['validity']['valid']``).
    """
    grouped: Dict[str, List[dict]] = {}
    for r in runs:
        valid = r.get("valid")
        if valid is None:
            valid = r.get("validity", {}).get("valid", False)
        if not valid:
            continue
        label = r.get("policy") or r.get("controller_label", "")
        grouped.setdefault(label, []).append(r)
    return grouped


def _build_markdown(summary: Dict[str, dict]) -> str:
    lines: List[str] = []
    lines.append("# Experiment Report")
    lines.append("")
    lines.append(f"Generated by `experiments.aggregate`.")
    lines.append("")
    # Per-policy table
    for policy, summary_row in sorted(summary.items()):
        lines.append(f"## Policy: `{policy}`")
        lines.append("")
        lines.append(f"- valid runs: **{summary_row['n_valid']}** "
                     f"of {summary_row['n_runs']}")
        lines.append("")
        lines.append("| metric | mean | std | 95% CI |")
        lines.append("| --- | ---: | ---: | ---: |")
        for metric in _METRICS:
            stats = summary_row["metrics"][metric]
            lines.append(
                f"| {metric} | {stats['mean']:.4f} "
                f"| {stats['std']:.4f} "
                f"| [{stats['ci_low']:.4f}, {stats['ci_high']:.4f}] |"
            )
        lines.append("")
    return "\n".join(lines)


def aggregate(input_path: str, output_path: str) -> Dict[str, object]:
    """Read the runner JSON, compute stats, write JSON + Markdown."""
    with open(input_path) as f:
        report = json.load(f)
    runs = report.get("runs", [])
    per_policy = _per_policy(runs)

    summary: Dict[str, dict] = {}
    metrics_by_policy: Dict[str, Dict[str, List[float]]] = {}
    for policy, items in per_policy.items():
        metrics: Dict[str, List[float]] = {}
        for metric in _METRICS:
            metrics[metric] = [float(r.get(metric, 0.0)) for r in items]
        metrics_by_policy[policy] = metrics
        summary[policy] = {
            "n_runs": report.get("n_seeds", 0) * len(per_policy)
                       if not items else len(items),
            "n_valid": len(items),
            "metrics": {
                metric: {
                    "mean":   mean(vals),
                    "std":    std(vals),
                    "ci_low": ci95(vals)[0],
                    "ci_high": ci95(vals)[1],
                }
                for metric, vals in metrics.items()
            },
        }

    # Paired comparisons against the first policy (typically random as the
    # common denominator). NOTE: this assumes equal-seed pairing.
    base = None
    paired: Dict[str, dict] = {}
    for policy in sorted(metrics_by_policy.keys()):
        if base is None:
            base = policy
            continue
        paired[policy] = {}
        for metric in _METRICS:
            base_vals = metrics_by_policy[base].get(metric, [])
            test_vals = metrics_by_policy[policy].get(metric, [])
            n = min(len(base_vals), len(test_vals))
            if n < 2:
                continue
            t = paired_t(base_vals[:n], test_vals[:n])
            sig = is_significant(t, n=n)
            paired[policy][metric] = {
                "t": round(t, 4),
                "n": n,
                "significant": bool(sig),
            }

    out = {
        "input":   os.path.basename(input_path),
        "per_policy_stats": summary,
        "paired_comparisons_vs_first_policy": paired,
    }
    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)
    with open(output_path, "w") as f:
        json.dump(out, f, indent=2, sort_keys=True)
    md_path = os.path.splitext(output_path)[0] + ".md"
    with open(md_path, "w") as f:
        f.write(_build_markdown(out["per_policy_stats"]))
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input", required=True,
        help="JSON output of experiments.runner",
    )
    parser.add_argument(
        "--output", default="experiments/results/REPORT.json",
    )
    args = parser.parse_args()

    out = aggregate(args.input, args.output)
    print(f"Wrote {args.output}")
    md = os.path.splitext(args.output)[0] + ".md"
    print(f"Wrote {md}")
    for name, s in out["per_policy_stats"].items():
        print(f"  {name}: valid={s['n_valid']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())